// Generates the canonical list of indexable pages by mirroring app/sitemap.ts.
// Outputs:
//   INDEXABLE-PAGES.md  — grouped Markdown inventory (human-readable)
//   indexable-urls.txt  — flat list of full URLs (Search Console submission)
//
// Run: node scripts/list-indexable-pages.mjs
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const BASE_URL = "https://www.theproudpaintbrush.com";

// --- City slugs: parsed from lib/cities.ts (top-level `slug:` entries) ---
const citiesSrc = fs.readFileSync(path.join(ROOT, "lib", "cities.ts"), "utf-8");
const citySlugs = [...citiesSrc.matchAll(/^ {4}slug:\s*"([^"]+)"/gm)].map((m) => m[1]);

// --- Service slugs from content/services/<parent> ---
const serviceSlugs = (parent) => {
  const dir = path.join(ROOT, "content", "services", parent);
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter((f) => f.endsWith(".json")).map((f) => f.replace(/\.json$/, "")).sort();
};

// --- Recursive page keys from content/pages ---
const walk = (dir, base = "") => {
  if (!fs.existsSync(dir)) return [];
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = base ? `${base}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...walk(path.join(dir, entry.name), rel));
    else if (entry.name.endsWith(".json")) out.push(rel.replace(/\.json$/, ""));
  }
  return out;
};
const pageKeys = walk(path.join(ROOT, "content", "pages")).sort();

// --- Slug lists from simple dirs ---
const dirSlugs = (...p) => {
  const dir = path.join(ROOT, ...p);
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter((f) => f.endsWith(".json")).map((f) => f.replace(/\.json$/, "")).sort();
};
const projectSlugs = dirSlugs("content", "projects");
const blogSlugs = dirSlugs("content", "blog");

// --- Build groups (mirrors sitemap.ts order) ---
const groups = [
  ["Static pages", [
    "", "/exterior-painting", "/interior-painting", "/cabinet-painting",
    "/our-story", "/our-vision", "/core-values", "/testimonials",
    "/faq", "/contact", "/blog", "/projects",
  ]],
  ["Exterior — city pages", citySlugs.map((c) => `/exterior-painting/${c}`)],
  ["Interior — city pages", citySlugs.map((c) => `/interior-painting/${c}`)],
  ["Cabinet — city pages", citySlugs.map((c) => `/cabinet-painting/${c}`)],
  ["Fence staining — city pages", citySlugs.map((c) => `/exterior-painting/fence-staining/${c}`)],
  ["Interior — service detail pages", serviceSlugs("interior").map((s) => `/interior-painting/${s}`)],
  ["Exterior — service detail pages", serviceSlugs("exterior").map((s) => `/exterior-painting/${s}`)],
  ["Content pages", pageKeys.map((k) => `/${k}`)],
  ["Project case studies", projectSlugs.map((s) => `/projects/${s}`)],
  ["Blog posts", blogSlugs.map((s) => `/blog/${s}`)],
];

const total = groups.reduce((n, [, paths]) => n + paths.length, 0);

// --- Write Markdown inventory ---
const md = [];
md.push("# Indexable Pages");
md.push("");
md.push(`Generated by \`scripts/list-indexable-pages.mjs\` — mirrors \`app/sitemap.ts\`.`);
md.push("");
md.push(`**Total: ${total} URLs.** All are listed in \`sitemap.xml\` and crawlable per \`robots.ts\` (no \`noindex\`).`);
md.push("");
for (const [name, paths] of groups) {
  md.push(`## ${name} — ${paths.length}`);
  md.push("");
  for (const p of paths) md.push(`- \`${p === "" ? "/" : p}\``);
  md.push("");
}
fs.writeFileSync(path.join(ROOT, "INDEXABLE-PAGES.md"), md.join("\n"));

// --- Write flat URL list (full absolute URLs) ---
const urls = groups.flatMap(([, paths]) => paths.map((p) => `${BASE_URL}${p}`));
fs.writeFileSync(path.join(ROOT, "indexable-urls.txt"), urls.join("\n") + "\n");

console.log(`cities=${citySlugs.length} interiorSvc=${serviceSlugs("interior").length} exteriorSvc=${serviceSlugs("exterior").length} pages=${pageKeys.length} projects=${projectSlugs.length} blog=${blogSlugs.length}`);
console.log(`Wrote INDEXABLE-PAGES.md and indexable-urls.txt — ${total} URLs total.`);
